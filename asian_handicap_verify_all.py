# 三、亚盘预测模型
# ============================================================
def predict_asian(odds_chu, asian_chu, odds_zhong, asian_zhong, same_home_wr, same_away_wr):
    """
    预测亚盘方向
    返回: (direction, score, reasons)  direction in {'主','客','中'}
    信号:
      1. 主队水位变化 (终-初): 下降=>利好主队
      2. 盘口升降: 终盘让球更深(数值更小)=>升盘=>利好主队
      3. 欧赔终盘隐含概率: 主胜概率显著高于客胜=>利好主队
      4. 相同盘口赢盘率: 主队主场赢盘率 > 客队客场赢盘率=>利好主队
    """
    score = 0.0
    reasons = []

    # 1. 水位变化
    if asian_chu and asian_zhong:
        dh = asian_zhong[0] - asian_chu[0]  # 主水变化
        if dh < -0.05:
            score += 1.0; reasons.append(f"主水大降{dh:+.3f}")
        elif dh < -0.01:
            score += 0.5; reasons.append(f"主水小降{dh:+.3f}")
        elif dh > 0.05:
            score -= 1.0; reasons.append(f"主水大升{dh:+.3f}")
        elif dh > 0.01:
            score -= 0.5; reasons.append(f"主水小升{dh:+.3f}")

    # 2. 盘口升降
    if asian_chu and asian_zhong:
        lo = handicap_to_num(asian_chu[1])
        ll = handicap_to_num(asian_zhong[1])
        if lo is not None and ll is not None:
            if ll < lo:
                score += 1.0; reasons.append(f"升盘({asian_chu[1]}→{asian_zhong[1]})")
            elif ll > lo:
                score -= 1.0; reasons.append(f"降盘({asian_chu[1]}→{asian_zhong[1]})")

    # 3. 欧赔隐含概率 (用终盘)
    if odds_zhong and len(odds_zhong) == 3:
        ph = 1.0 / odds_zhong[0]
        pd = 1.0 / odds_zhong[1]
        pa = 1.0 / odds_zhong[2]
        tot = ph + pd + pa
        ph /= tot; pa /= tot
        if ph - pa > 0.20:
            score += 1.0; reasons.append(f"欧赔主胜{ph*100:.0f}%>>客{pa*100:.0f}%")
        elif ph - pa > 0.10:
            score += 0.5; reasons.append(f"欧赔主胜{ph*100:.0f}%>客{pa*100:.0f}%")
        elif pa - ph > 0.20:
            score -= 1.0; reasons.append(f"欧赔客胜{pa*100:.0f}%>>主{ph*100:.0f}%")
        elif pa - ph > 0.10:
            score -= 0.5; reasons.append(f"欧赔客胜{pa*100:.0f}%>主{ph*100:.0f}%")

    # 4. 相同盘口赢盘率对比
    if same_home_wr is not None and same_away_wr is not None:
        diff = same_home_wr - same_away_wr
        if diff > 15:
            score += 1.0; reasons.append(f"同盘主优({same_home_wr:.0f}%>{same_away_wr:.0f}%)")
        elif diff > 5:
            score += 0.5; reasons.append(f"同盘主略优({same_home_wr:.0f}%>{same_away_wr:.0f}%)")
        elif diff < -15:
            score -= 1.0; reasons.append(f"同盘客优({same_away_wr:.0f}%>{same_home_wr:.0f}%)")
        elif diff < -5:
            score -= 0.5; reasons.append(f"同盘客略优({same_away_wr:.0f}%>{same_home_wr:.0f}%)")

    if score >= 1.0:
        direction = "主"
    elif score <= -1.0:
        direction = "客"
    else:
        direction = "中"
    return direction, score, reasons


