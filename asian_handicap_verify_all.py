HANDICAP_MAP = {
    "平手": 0, "平/半": 0.25, "半球": 0.5, "半/一": 0.75,
    "一球": 1.0, "一/球半": 1.25, "球半": 1.5, "球半/两": 1.75,
    "两球": 2.0, "两/两球半": 2.25, "两球半": 2.5, "两球半/三": 2.75,
    "三球": 3.0, "三/三球半": 3.25, "三球半": 3.5, "三球半/四": 3.75,
    "四球": 4.0,
}


def handicap_to_num(h):
    """盘口文字转数值(主队视角). 无*: 主队让球(负); 有*: 主队受让(正)"""
    if not h:
        return None
    h = h.strip()
    receiving = h.startswith("*")
    if receiving:
        h = h[1:]
    if h in HANDICAP_MAP:
        val = HANDICAP_MAP[h]
    else:
        # 尝试解析分数盘口如 "1.5" 或 "1/1.5"
        if "/" in h:
            try:
                parts = h.split("/")
                val = (float(parts[0]) + float(parts[1])) / 2
            except Exception:
                return None
        else:
            try:
                val = float(h)
            except Exception:
                return None
    # 主队让球为负, 主队受让为正
    return -val if not receiving else val


