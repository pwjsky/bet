# 四、实际赛果计算
# ============================================================
def calc_handicap_result(home_goals, away_goals, handicap_num):
    """
    计算亚盘结果方向
    handicap_num: 主队视角让球数 (负=主队让, 正=主队受让)
    返回: '主' | '客' | '走水'
    对于四分之一盘口(平/半等), 平局自动归入受让方方向
    """
    if handicap_num is None:
        return None
    adjusted = home_goals + handicap_num
    diff = adjusted - away_goals
    if diff > 0:
        return "主"
    elif diff < 0:
        return "客"
    else:
        return "走水"


